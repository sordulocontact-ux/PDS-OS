// Writes the Supabase Auth e-mails (supabase/templates) from the frame every
// e-mail shares (lib/email/layout.ts) and their words (lib/i18n/fr/emails.ts):
// one look for all e-mails. Run `pnpm email:templates` after changing either,
// then paste each file into Supabase (prod and pre-prod): Authentication ›
// Emails › Templates, with the subject written at the top of the file.
// Locally, supabase/config.toml reads them directly.
import { writeFileSync } from "node:fs";

import {
  button,
  emailDocument,
  fallbackLink,
  heading,
  note,
  paragraph,
  rule,
} from "../lib/email/layout.ts";
import { emails } from "../lib/i18n/fr/emails.ts";

// Supabase's Go template tags. Values Supabase fills are escaped by it.
const GREETING = `{{ if .Data.first_name }}${emails.greetingOf("{{ .Data.first_name }}")}{{ else }}${emails.greeting}{{ end }}`;
// token_hash links, handled by /auth/confirm: they work from any browser or
// device. {{ .RedirectTo }} = NEXT_PUBLIC_SITE_URL + /auth/confirm, which must
// be in the auth redirect allow-list.
const link = (type) =>
  `{{ .RedirectTo }}?token_hash={{ .TokenHash }}&amp;type=${type}`;

function header(name, subject) {
  return `<!--
  "${name}" template, generated by scripts/email-templates.mjs: do not edit,
  change lib/email/layout.ts or lib/i18n/fr/emails.ts and run
  \`pnpm email:templates\`. Paste it in Supabase (prod and pre-prod):
  Authentication › Emails › Templates.
  Subject: ${subject}
-->
`;
}

function write(file, name, t, blocks) {
  const html = emailDocument({
    title: t.title,
    brand: emails.brand,
    preheader: t.preheader,
    blocks,
    footer: emails.footer,
  });
  writeFileSync(
    new URL(`../supabase/templates/${file}`, import.meta.url),
    header(name, t.subject) + html,
  );
}

const c = emails.confirmation;
write("confirmation.html", "Confirm signup", c, [
  heading(c.title),
  paragraph(GREETING),
  paragraph(c.intro),
  button(c.action, link("email")),
  note(c.next),
  rule(),
  note(c.ignore),
  fallbackLink(emails.buttonFallback, link("email")),
]);

const r = emails.recovery;
write("recovery.html", "Reset password", r, [
  heading(r.title),
  paragraph(GREETING),
  paragraph(r.intro("{{ .Email }}")),
  button(r.action, link("recovery")),
  note(r.once),
  rule(),
  note(r.ignore),
  fallbackLink(emails.buttonFallback, link("recovery")),
]);

console.log("supabase/templates: confirmation.html, recovery.html");
