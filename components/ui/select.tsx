// indicator "check" (default): a tick on the right of the chosen item.
// "checkbox": a box on the left of every item, drawn like Checkbox (blue
// outline, pale fill, blue tick) once ticked — tells at a glance that several can be chosen (multiple).
function SelectItem({
  className,
  children,
  indicator = "check",
  ...props
}: SelectPrimitive.Item.Props & { indicator?: "check" | "checkbox" }) {
  return (
    <SelectPrimitive.Item
      data-slot="select-item"
      className={cn(
        "group/item relative flex w-full cursor-default items-center gap-1.5 rounded-md py-1 pl-1.5 text-sm outline-hidden select-none focus:bg-accent focus:text-accent-foreground not-data-[variant=destructive]:focus:**:text-accent-foreground data-disabled:pointer-events-none data-disabled:opacity-50 [&_svg]:pointer-events-none [&_svg]:shrink-0 [&_svg:not([class*='size-'])]:size-4 *:[span]:last:flex *:[span]:last:items-center *:[span]:last:gap-2",
        indicator === "check" ? "pr-8" : "gap-2.5 pr-2",
        className
      )}
      {...props}
    >
      {indicator === "checkbox" && (
        // Drawn, not a native input: an option is not a form control of its
        // own (the list carries aria-multiselectable, the option aria-selected).
        // `data-[selected]`, not `data-selected`: shadcn's variant only matches
        // data-selected="true", Base UI sets the attribute empty.
        <span
          aria-hidden
          className="flex size-4 shrink-0 items-center justify-center rounded-sm border border-[color:var(--border-default)] bg-[var(--control-bg)] group-data-[selected]/item:border-selection group-data-[selected]/item:bg-selection-bg"
        >
          <CheckboxMark
            kind="check"
            className="size-3 text-selection opacity-0 group-data-[selected]/item:opacity-100"
          />
        </span>
      )}
      {/* A long option wraps inside the list, never under the tick (Sacha
          07/11/2026: a Dispositif lever ran past the popup). */}
      <SelectPrimitive.ItemText className="flex min-w-0 flex-1 gap-2 break-words whitespace-normal">
        {children}
      </SelectPrimitive.ItemText>
      {indicator === "check" && (
        <SelectPrimitive.ItemIndicator
          render={
            <span className="pointer-events-none absolute right-2 flex size-4 items-center justify-center" />
          }
        >
          <IconCheck className="pointer-events-none" />
        </SelectPrimitive.ItemIndicator>
      )}
    </SelectPrimitive.Item>
  )
}

