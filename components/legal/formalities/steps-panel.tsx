"use client";

import { useLegalAction } from "@/components/legal/use-legal-action";
import { SignaturesList } from "@/components/legal/formalities/signatures-list";
import { Button } from "@/components/ui/button";
import { DialogButton } from "@/components/ui/dialog-button";
import { ReasonForm } from "@/components/ui/reason-form";
import { ToneCallout } from "@/components/ui/tone-callout";
import { legalFormalities } from "@/lib/i18n/fr/legal-formalities";
import { formalityStep } from "@/lib/legal/formalities/step-actions";
import type { FormalityView } from "@/lib/legal/formalities/types";
import { formatInstant } from "@/lib/utils/instant";

import { DepositForm } from "./deposit-form";
import { SacemAnswerForm } from "./sacem-answer-form";

const fr = { legalFormalities };

/** From the bulletin to the SACEM's answer (it is generated by the
 * dossier): the signatures (or a partial declaration), the deposit with its
 * receipt, the processing, the answer — registered, to correct or rejected,
 * each with its proof (JUR-03). A gesture that asks for something opens a
 * dialog; no frise. */
export function StepsPanel({
  projectId,
  f,
}: {
  projectId: string;
  f: FormalityView;
}) {
  const t = fr.legalFormalities.page;
  const tr = fr.legalFormalities.transitions;
  const { pending, run } = useLegalAction();
  const proof = (url: string | null, label: string) =>
    url && (
      <Button
        variant="ghost"
        size="sm"
        nativeButton={false}
        render={<a href={url} target="_blank" rel="noreferrer" />}
      >
        {label}
      </Button>
    );

  return (
    // Nothing to do or show yet (the dossier still being filled): no empty
    // box, which would add its gap above the dossier.
    <div className="flex flex-col gap-4 [&:not(:has(>:not(:empty)))]:hidden">
      {f.status === "rejected" && (
        <ToneCallout tone="danger">
          {t.rejected(
            f.rejectedAt ? formatInstant(f.rejectedAt) : "",
            f.rejectionReason ?? "",
          )}
        </ToneCallout>
      )}
      <div className="flex flex-wrap items-center gap-2 empty:hidden">
        {f.status === "signatures_pending" && (
          <DialogButton
            label={t.partial}
            variant="outline"
            size="sm"
            title={t.partial}
            description={t.partialReason}
          >
            {(close) => (
              <ReasonForm
                label={t.partialReason}
                submitLabel={t.partial}
                doneMessage={tr.partial}
                run={(reason) =>
                  formalityStep(projectId, f.id, "partial", reason)
                }
                onDone={() => {
                  close();
                }}
              />
            )}
          </DialogButton>
        )}
        {f.status === "ready_to_submit" && (
          <DialogButton
            label={t.submit}
            size="sm"
            title={t.submit}
            description={t.submitBody}
          >
            {(close) => (
              <DepositForm
                projectId={projectId}
                formalityId={f.id}
                onDone={close}
              />
            )}
          </DialogButton>
        )}
        {f.status === "submitted" && (
          <Button
            size="sm"
            variant="outline"
            disabled={pending}
            onClick={() =>
              run(
                () => formalityStep(projectId, f.id, "processing", ""),
                undefined,
                tr.processing,
              )
            }
          >
            {t.processing}
          </Button>
        )}
        {["submitted", "processing"].includes(f.status) && (
          <DialogButton
            label={t.answer}
            size="sm"
            title={t.answer}
            description={t.answerBody}
          >
            {(close) => (
              <SacemAnswerForm
                projectId={projectId}
                formalityId={f.id}
                onDone={close}
              />
            )}
          </DialogButton>
        )}
        {f.status === "rejected" && (
          <Button
            size="sm"
            disabled={pending}
            onClick={() =>
              run(
                () => formalityStep(projectId, f.id, "restart", ""),
                undefined,
                tr.restart,
              )
            }
          >
            {t.restart}
          </Button>
        )}
        {proof(f.submissionFileUrl, t.viewDeposit)}
        {proof(f.completionFileUrl, t.viewRegistration)}
      </div>
      <SignaturesList projectId={projectId} f={f} />
    </div>
  );
}
