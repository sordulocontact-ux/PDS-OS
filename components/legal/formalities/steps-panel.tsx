"use client";

import { useState } from "react";

import { Field } from "@/components/auth/field";
import { TextareaField } from "@/components/auth/textarea-field";
import { OptionSelect } from "@/components/projects/option-select";
import { useLegalAction } from "@/components/legal/use-legal-action";
import { Button } from "@/components/ui/button";
import { SignaturesList } from "@/components/legal/formalities/signatures-list";
import { ProcessingSteps } from "@/components/ui/processing-steps";
import { formalityTimeline } from "@/lib/legal/formalities/timeline";
import { fr } from "@/lib/i18n/fr";
import {
  completeFormality,
  formalityStep,
  requireFormalityAction,
} from "@/lib/legal/formalities/step-actions";
import { SACEM_725_FIELDS } from "@/lib/legal/formalities/definition";
import type { FormalityView } from "@/lib/legal/formalities/types";

type Open = "partial" | "submit" | "correction" | "complete" | null;

/** From the bulletin to the registration (it is generated by the dossier):
 * collect the signatures (or a partial declaration), record the deposit,
 * the processing, a correction, the result with its proof. */
export function StepsPanel({
  projectId,
  f,
}: {
  projectId: string;
  f: FormalityView;
}) {
  const t = fr.legalFormalities.page;
  const [open, setOpen] = useState<Open>(null);
  const [text, setText] = useState("");
  const [extra, setExtra] = useState({ externalId: "", iswc: "", field: "" });
  const { pending, run } = useLegalAction();
  const close = () => {
    setOpen(null);
    setText("");
  };

  return (
    <div className="flex flex-col gap-4">
      {/* Where the declaration stands, step by step (JUR-26). */}
      <ProcessingSteps
        idle
        label={fr.legalFormalities.timeline.label}
        doneLabel={fr.legalFormalities.timeline.done}
        steps={formalityTimeline(f)}
      />
      <div className="flex flex-wrap gap-2">
        {f.status === "signatures_pending" && (
          <Button
            size="sm"
            variant="outline"
            onClick={() => setOpen("partial")}
          >
            {t.partial}
          </Button>
        )}
        {f.status === "ready_to_submit" && (
          <Button size="sm" onClick={() => setOpen("submit")}>
            {t.submit}
          </Button>
        )}
        {f.status === "submitted" && (
          <Button
            size="sm"
            variant="outline"
            disabled={pending}
            onClick={() =>
              run(
                () => formalityStep(projectId, f.id, "processing", ""),
                undefined,
                fr.legalFormalities.transitions.processing,
              )
            }
          >
            {t.processing}
          </Button>
        )}
        {["submitted", "processing"].includes(f.status) && (
          <>
            <Button
              size="sm"
              variant="outline"
              onClick={() => setOpen("correction")}
            >
              {t.correction}
            </Button>
            <Button size="sm" onClick={() => setOpen("complete")}>
              {t.complete}
            </Button>
          </>
        )}
      </div>

      {open && (
        <div className="flex flex-col gap-2 rounded-xl border p-3">
          {open === "correction" && (
            <OptionSelect
              name={`${f.id}-correction-field`}
              label={t.correctionFields}
              required
              items={Object.fromEntries(
                SACEM_725_FIELDS.map((x) => [
                  x.key,
                  fr.legalFormalities.fields[x.key],
                ]),
              )}
              onValueChange={(v) => setExtra((e) => ({ ...e, field: v }))}
            />
          )}
          <TextareaField
            name={`${f.id}-${open}`}
            label={
              open === "partial"
                ? t.partialReason
                : open === "submit"
                  ? t.submitProof
                  : open === "correction"
                    ? t.correctionNote
                    : t.completeProof
            }
            aria-required
            rows={2}
            maxLength={2000}
            value={text}
            onChange={(e) => setText(e.target.value)}
          />
          {open === "complete" && (
            <div className="grid gap-2 sm:grid-cols-2">
              <Field
                name={`${f.id}-external`}
                label={t.externalId}
                value={extra.externalId}
                onChange={(e) =>
                  setExtra((x) => ({ ...x, externalId: e.target.value }))
                }
              />
              <Field
                name={`${f.id}-iswc`}
                label={t.iswc}
                value={extra.iswc}
                onChange={(e) =>
                  setExtra((x) => ({ ...x, iswc: e.target.value }))
                }
              />
            </div>
          )}
          <div className="flex justify-end gap-2">
            <Button size="sm" variant="ghost" onClick={close}>
              {t.cancel}
            </Button>
            <Button
              size="sm"
              disabled={
                pending ||
                !text.trim() ||
                (open === "correction" && !extra.field)
              }
              onClick={() =>
                run(
                  () =>
                    open === "partial" || open === "submit"
                      ? formalityStep(projectId, f.id, open, text)
                      : open === "correction"
                        ? requireFormalityAction(
                            projectId,
                            f.id,
                            [extra.field],
                            text,
                          )
                        : completeFormality(
                            projectId,
                            f.id,
                            text,
                            extra.externalId,
                            extra.iswc,
                          ),
                  close,
                  fr.legalFormalities.transitions[open ?? "complete"],
                )
              }
            >
              {t.confirm}
            </Button>
          </div>
        </div>
      )}

      <SignaturesList projectId={projectId} f={f} />
    </div>
  );
}
