import { VersionView } from "@/components/strategy/documents/version-view";
import { DirectionStep } from "@/components/strategy/generator/direction-step";
import { FormatsStep } from "@/components/strategy/generator/formats-step";
import { GenerateButton } from "@/components/strategy/generator/generate-button";
import { GeneratorLocked } from "@/components/strategy/generator/generator-locked";
import { GeneratorShell } from "@/components/strategy/generator/generator-shell";
import { PagesStep } from "@/components/strategy/generator/pages-step";
import { PhasesStep } from "@/components/strategy/generator/phases-step";
import { PlanIntro } from "@/components/strategy/generator/plan-intro";
import { VisualsStep } from "@/components/strategy/generator/visuals-step";
import { StrategyTabs } from "@/components/strategy/strategy-tabs";
import { ToneCallout } from "@/components/ui/tone-callout";
import { routes } from "@/lib/auth/redirects";
import { fr } from "@/lib/i18n/fr";
import { loadReleasePlanConfig } from "@/lib/strategy/documents/drafts";
import { generatorLock, stepOf } from "@/lib/strategy/documents/generator-gate";
import {
  orderedPages,
  RELEASE_PLAN_PAGES,
} from "@/lib/strategy/documents/model";
import { offsetsOf, proposePhases } from "@/lib/strategy/documents/phases";
import {
  emptyPlanPages,
  formatsFrom,
  knownLines,
  releasePlanProgress,
} from "@/lib/strategy/documents/plan-steps";
import { loadDocumentSources } from "@/lib/strategy/documents/sources";
import { loadStrategyPage } from "@/lib/strategy/page-data";
import { versionsOf } from "@/lib/strategy/workspace";

/**
 * The Plan de sortie generator (ticket § 11): eight steps, one at a time
 * (?step=n). PO starts from the validated Brief and asks only for what is
 * missing; the document is generated by the server, never a blind export.
 */
export default async function ReleasePlanPage({
  params,
  searchParams,
}: PageProps<"/app/projects/[projectId]/strategy/release-plan">) {
  const { projectId } = await params;
  const page = await loadStrategyPage(projectId);
  const t = fr.strategyDocs;
  const tabs = <StrategyTabs projectId={projectId} />;
  const lock = generatorLock(page);
  const sources = lock ? null : await loadDocumentSources(page);
  if (lock || !sources)
    return (
      <div className="flex flex-col gap-6 pt-6">
        {tabs}
        <GeneratorLocked
          projectId={projectId}
          reason={lock ?? t.generator.needsBrief}
        />
      </div>
    );

  const { data, ctx, access, project } = page;
  const config = await loadReleasePlanConfig(projectId);
  const versions = versionsOf(ctx.documents, "release_plan");
  const step = stepOf((await searchParams).step, 8);
  const href = (n: number) => routes.projectStrategyReleasePlan(projectId, n);
  const progress = releasePlanProgress(config, versions.length > 0);
  const steps = t.plan.steps.map((name, i) => ({
    name,
    href: href(i + 1),
    done: progress[i],
  }));
  const chosen = new Set(
    (config.visuals ?? []).map((v) => `${v.source}:${v.id}`),
  );
  const generate = (
    <GenerateButton
      projectId={projectId}
      kind="release_plan"
      label={versions.length ? t.plan.regenerate : t.plan.generate}
      pendingLabel={t.plan.generating}
      variant={versions.length ? "outline" : "default"}
    />
  );

  const screen = (() => {
    switch (step) {
      case 1:
        return (
          <PlanIntro
            title={t.plan.introTitle}
            body={t.plan.introBody}
            known={knownLines(sources.brief)}
            toComplete={(
              ["phases", "formats", "visuals", "direction", "pages"] as const
            ).map((key, i) => ({
              key,
              label: t.plan.toCompleteItems[key],
              done: progress[i + 1],
            }))}
            startHref={href(2)}
          />
        );
      case 2:
        return (
          <PhasesStep
            projectId={projectId}
            initial={
              config.phases ??
              proposePhases(data.milestones, data.referenceDate)
            }
            offsets={offsetsOf(data.milestones, data.referenceDate)}
            nextHref={href(3)}
          />
        );
      case 3:
        return (
          <FormatsStep
            projectId={projectId}
            initial={config.formats ?? formatsFrom(data.deliverables)}
            nextHref={href(4)}
          />
        );
      case 4:
        return (
          <VisualsStep
            projectId={projectId}
            organizationId={access.organizationId ?? ""}
            kind="release_plan"
            candidates={sources.visuals}
            initial={config.visuals ?? []}
            nextHref={href(5)}
          />
        );
      case 5:
        return (
          <DirectionStep
            projectId={projectId}
            imageUrls={sources.visuals
              .filter((v) => chosen.has(`${v.source}:${v.id}`))
              .map((v) => v.previewUrl)}
            saved={config.direction}
            nextHref={href(6)}
          />
        );
      case 6:
        return (
          <PagesStep
            projectId={projectId}
            kind="release_plan"
            initial={orderedPages(RELEASE_PLAN_PAGES, config.pages)}
            empty={emptyPlanPages(
              sources.brief,
              config,
              data.milestones.length,
            )}
            nextHref={href(7)}
          />
        );
      case 7:
        return (
          <section className="flex flex-col items-start gap-4">
            <h2 className="text-display-sm font-semibold">
              {t.plan.generateTitle}
            </h2>
            <p className="max-w-prose text-body-md text-muted-foreground">
              {t.plan.generateBody}
            </p>
            {!progress.slice(1, 6).every(Boolean) && (
              <ToneCallout tone="warning">
                {t.plan.generateIncomplete}
              </ToneCallout>
            )}
            {generate}
          </section>
        );
      default:
        return versions[0] ? (
          <VersionView
            projectId={projectId}
            projectTitle={project.title}
            version={versions[0]}
            versions={versions}
            meId={access.personId}
            owner
            director={data.validators[0]?.name ?? null}
            creatives={ctx.creatives}
            editHref={href(6)}
            extra={generate}
          />
        ) : (
          <ToneCallout tone="neutral">{t.plan.noVersion}</ToneCallout>
        );
    }
  })();

  return (
    <div className="flex flex-col gap-6 pt-6">
      {tabs}
      <GeneratorShell
        label={t.generator.stepsLabel}
        steps={steps}
        current={step}
      >
        {screen}
      </GeneratorShell>
    </div>
  );
}
